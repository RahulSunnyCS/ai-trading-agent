"""BL-095 Phase 1 check: rotation/portfolio.py reproduces BL-055's totals and drawdowns.

BL-055 (research/bl055/evaluate.py) stopped the combined MTM of three benchmark mixes at 8k / 10k /
12.5k and logged total P&L and max drawdown per level in its item. This feeds the same curves
(`curves_*.pkl`, generated by research/bl055/extract_curves.py, git-ignored) through
`apply_book` and compares to those logged figures to the rupee. Not part of the product.

    uv run python research/bl095/reproduce_bl055.py --curves-dir <dir holding the pkl files>
"""

from __future__ import annotations

import argparse
import pickle
import sys
from pathlib import Path

from option_backtesting.rotation.portfolio import apply_book, member_from_curve

NAMES = {
    "W": "nifty_widesl_917_otm1",
    "D": "nifty_dir_924_itm1_sl21_recost",
    "B": "nifty_buy_range_breakout",
}
MIXES = {"B1": {"W": 5}, "B2": {"W": 3, "D": 2}, "B3": {"W": 4, "D": 1, "B": 1}}
LEVELS = [None, 8000, 10000, 12500]
# (total, max drawdown) as logged in backlog/BL-055-daily-portfolio-stop-loss.md
LOGGED = {
    ("B2", None): (947039, -167246),
    ("B2", 8000): (1061722, -96829),
    ("B2", 10000): (1034463, -131435),
    ("B2", 12500): (960386, -169014),
    ("B1", None): (872687, -225807),
    ("B1", 8000): (766668, -148038),
    ("B1", 10000): (813267, -203011),
    ("B1", 12500): (872687, -225807),
    ("B3", None): (929984, -210009),
    ("B3", 8000): (894013, -134560),
    ("B3", 10000): (975090, -163066),
    ("B3", 12500): (973335, -190369),
}


def max_drawdown(daily: list[float]) -> float:
    eq, peak, worst = 0.0, 0.0, 0.0
    for v in daily:
        eq += v
        peak = max(peak, eq)
        worst = min(worst, eq - peak)
    return worst


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--curves-dir", type=Path, required=True)
    args = ap.parse_args()
    cur = {}
    for key, name in NAMES.items():
        with open(args.curves_dir / f"curves_{name}.pkl", "rb") as fh:
            cur[key] = pickle.load(fh)
    days = sorted(set.intersection(*[set(c) for c in cur.values()]))
    print(f"{len(days)} days, {days[0]} -> {days[-1]}")
    bad = 0
    for mix, lots in MIXES.items():
        for level in LEVELS:
            daily = []
            for d in days:
                members = [
                    member_from_curve(k, n, cur[k][d]["curve"], cur[k][d]["gross"])
                    for k, n in lots.items()
                ]
                daily.append(apply_book(members, level).gross_with)
            total, dd = round(sum(daily)), round(max_drawdown(daily))
            want_total, want_dd = LOGGED[(mix, level)]
            # the item logged whole rupees of a figure computed in floats: allow rounding of 1
            ok = abs(total - want_total) <= 1 and abs(dd - want_dd) <= 1
            bad += not ok
            print(
                f"{mix} {str(level or 'no stop'):>8}  total {total:>10,}  max DD {dd:>10,}  "
                f"logged {want_total:>10,} / {want_dd:>10,}  {'ok' if ok else 'MISMATCH'}"
            )
    print("all match" if not bad else f"{bad} mismatches")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
