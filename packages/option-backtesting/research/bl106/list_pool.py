"""BL-106: write the Group Leaders v1 pool (the pool's 94 sets, 556 variants) as a readable list,
straight from the frozen JSON files. Read-only; writes only group_leaders_v1.md in this folder.

    uv run python research/bl106/list_pool.py
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).parent
FAMILY = {"W": "Widesl", "D": "Dir", "B": "Buy"}
INDEX = {"N": "NIFTY", "S": "SENSEX"}
BAND = {
    "A": "09:17 to 10:02",
    "B": "10:17 to 12:02",
    "C": "12:17 to 14:02",
    "D": "14:17 to 15:17",
}


def fmt_trail(t) -> str:
    return "none" if not t else f"{t[0]} / {t[1]}"


def fmt_reentry(r) -> str:
    if not r:
        return "none"
    until = f" until {r[2]}" if r[2] else ""
    return f"{r[0]} x{r[1]}{until}"


def describe(s: dict) -> str:
    p = s["params"]
    if s["family"] == "B":
        target = "none" if not p.get("target") else f"{p['target']}%"
        return (
            f"{p['strike']}, range {p['range']} min ({p['source']}), SL {p['sl']}%, target {target}, "
            f"trail {fmt_trail(p.get('trail'))}, day stop ₹{p['mtm']:,}"
        )
    base = (
        f"{p['strike']}, SL {p['sl']}%, trail {fmt_trail(p.get('trail'))}, day stop ₹{p['mtm']:,}"
    )
    if s["family"] == "W":
        base += f", exit {p.get('exit', '15:28')}"
    return base + f", re-entry {fmt_reentry(p.get('reentry'))}"


def main() -> None:
    sets = json.loads((HERE / "pool_sets_2026-10-15.json").read_text())
    ext = json.loads((HERE / "pool_sets_ext_2026-10-15.json").read_text())
    cells = json.loads((HERE / "pool_cells_2026-10-15.json").read_text()) + json.loads(
        (HERE / "pool_cells_ext_2026-10-15.json").read_text()
    )
    for s in ext:
        s["ext"] = True
    all_sets = sets + ext
    per_set = Counter()
    for c in cells:
        per_set[c["name"].rsplit("_", 1)[0]] += 1
    groups: dict[tuple, list] = defaultdict(list)
    for s in all_sets:
        groups[(s["family"], s["index"], s["band"])].append(s)
    lines = [
        "# Group Leaders v1 (BL-106's New-556)",
        "",
        f"{len(all_sets)} sets in {len(groups)} groups, {len(cells)} variants. A *group* is a strategy "
        "family × index × time band; each group keeps its top few settings from the first year "
        "(2024-10-09 to 2025-10-08), and each setting is run at every entry time of its band "
        "(A 4 slots, B 8, C 8, D 5; Buy has no 15:17). The three NIFTY Dir ITM1 sets are the owner's "
        "ITM amendment (marked *ITM*, exploratory).",
        "",
        "Generated by `research/bl106/list_pool.py` from the frozen `pool_*_2026-10-15.json` files. "
        "'Year-1 ₹/day' is the setting's average per lot-day in the selection year, after charges.",
        "",
    ]
    for fam in "WDB":
        for idx in "NS":
            for band in "ABCD":
                g = groups.get((fam, idx, band))
                if not g:
                    lines += [f"## {FAMILY[fam]} · {INDEX[idx]} · {BAND[band]}", "", "No set.", ""]
                    continue
                slots = sorted(
                    {
                        c["slot"]
                        for c in cells
                        if (c["family"], c["index"]) == (fam, idx)
                        and c["name"].split("_")[1][1] == band
                    }
                )
                lines += [
                    f"## {FAMILY[fam]} · {INDEX[idx]} · {BAND[band]} ({len(slots)} slots, {len(g)} sets)",
                    "",
                    "| Set | Setting | Year-1 ₹/day | Variants |",
                    "|---|---|---:|---:|",
                ]
                for s in sorted(g, key=lambda x: x["k"]):
                    tag = f"{'wdb'['WDB'.index(fam)]}{band}{s['k']}"
                    name = f"{idx}_{tag}"
                    mark = " *ITM*" if s.get("ext") else ""
                    lines.append(
                        f"| `{name}`{mark} | {describe(s)} | {s['y1_avg_day_inr']:,.0f} | {per_set[name]} |"
                    )
                lines.append("")
    (HERE / "group_leaders_v1.md").write_text("\n".join(lines) + "\n")
    print(f"{len(all_sets)} sets, {len(groups)} groups, {len(cells)} variants")
    by_fam = Counter()
    for c in cells:
        by_fam[(FAMILY[c["family"]], INDEX[c["index"]])] += 1
    print(dict(sorted(by_fam.items())))


if __name__ == "__main__":
    main()
